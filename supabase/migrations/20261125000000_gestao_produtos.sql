CREATE SCHEMA gestao_produtos;

REVOKE ALL ON SCHEMA gestao_produtos FROM PUBLIC, anon, authenticated;

SET LOCAL search_path TO gestao_produtos, pg_catalog;

CREATE TABLE IF NOT EXISTS usuarios (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario TEXT UNIQUE NOT NULL,
    nome TEXT NOT NULL,
    email TEXT UNIQUE NOT NULL,
    senha_hash TEXT NOT NULL,
    salt TEXT NOT NULL,
    empresa TEXT DEFAULT '',
    cargo TEXT DEFAULT '',
    markup_padrao DOUBLE PRECISION DEFAULT 60.0,
    custo_adicional_padrao DOUBLE PRECISION DEFAULT 0.0,
    impostos_padrao TEXT DEFAULT '["ICMS ST", "FCP ST", "IPI", "II"]',
    criado_em TEXT NOT NULL,
    ultimo_login TEXT
);

CREATE TABLE IF NOT EXISTS historico_nfe (
    chave_acesso TEXT NOT NULL,
    numero TEXT,
    serie TEXT,
    data_emissao TEXT,
    fornecedor TEXT,
    cnpj_emit TEXT,
    valor_total DOUBLE PRECISION,
    arquivo_original TEXT,
    arquivo_salvo TEXT,
    data_importacao TEXT,
    usuario_id INTEGER NOT NULL,
    xml_original BYTEA,
    PRIMARY KEY (usuario_id, chave_acesso)
);

CREATE TABLE IF NOT EXISTS estoque_produtos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo TEXT NOT NULL,
    produto TEXT NOT NULL,
    unidade TEXT DEFAULT 'UN',
    quantidade_atual DOUBLE PRECISION DEFAULT 0.0,
    estoque_minimo DOUBLE PRECISION DEFAULT 5.0,
    custo_unitario DOUBLE PRECISION DEFAULT 0.0,
    preco_venda DOUBLE PRECISION DEFAULT 0.0,
    fornecedor_ultimo TEXT DEFAULT '',
    categoria TEXT DEFAULT 'Geral',
    usuario_id INTEGER,
    criado_em TEXT NOT NULL,
    atualizado_em TEXT NOT NULL,
    UNIQUE(codigo, usuario_id)
);

CREATE TABLE IF NOT EXISTS estoque_movimentacoes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produto_id INTEGER NOT NULL,
    codigo TEXT NOT NULL,
    tipo TEXT NOT NULL,
    quantidade DOUBLE PRECISION NOT NULL,
    quantidade_anterior DOUBLE PRECISION NOT NULL,
    quantidade_nova DOUBLE PRECISION NOT NULL,
    motivo TEXT,
    documento_ref TEXT,
    usuario_id INTEGER,
    usuario_nome TEXT DEFAULT '',
    data_hora TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS trilha_auditoria (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INTEGER,
    usuario_nome TEXT,
    acao TEXT NOT NULL,
    detalhes TEXT NOT NULL,
    ip TEXT DEFAULT '127.0.0.1',
    data_hora TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_usuarios_usuario ON usuarios(lower(usuario));

CREATE INDEX IF NOT EXISTS idx_usuarios_email ON usuarios(lower(email));

CREATE INDEX IF NOT EXISTS idx_nfe_usuario ON historico_nfe(usuario_id);

CREATE INDEX IF NOT EXISTS idx_estoque_usuario ON estoque_produtos(usuario_id);

CREATE INDEX IF NOT EXISTS idx_mov_usuario ON estoque_movimentacoes(usuario_id);

CREATE INDEX IF NOT EXISTS idx_auditoria_usuario ON trilha_auditoria(usuario_id);

CREATE TABLE tentativas_login (
    chave TEXT PRIMARY KEY,
    falhas DOUBLE PRECISION[] NOT NULL DEFAULT '{}',
    bloqueado_ate DOUBLE PRECISION NOT NULL DEFAULT 0
);

CREATE TABLE nfe_upload_partes (
    usuario_id INTEGER NOT NULL,
    lote UUID NOT NULL,
    arquivo INTEGER NOT NULL,
    parte INTEGER NOT NULL,
    conteudo BYTEA NOT NULL,
    expira_em TIMESTAMPTZ NOT NULL DEFAULT (now() + interval '1 hour'),
    PRIMARY KEY (usuario_id, lote, arquivo, parte)
);

CREATE INDEX idx_nfe_upload_expiracao ON nfe_upload_partes(expira_em);
